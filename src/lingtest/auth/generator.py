"""Generate reviewable auth plans and standalone pytest/httpx scripts."""

from __future__ import annotations

import json
from pathlib import Path

import yaml

from lingtest.auth.models import AuthHook, AuthPlan
from lingtest.models import TestCase


def write_auth_plan(plan: AuthPlan, path: Path) -> None:
    """Write a secret-free authentication plan as YAML or JSON."""

    path.parent.mkdir(parents=True, exist_ok=True)
    data = plan.model_dump(mode="json", exclude_none=True)
    if path.suffix.lower() == ".json":
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    elif path.suffix.lower() in {".yaml", ".yml"}:
        path.write_text(
            yaml.safe_dump(data, allow_unicode=True, sort_keys=False),
            encoding="utf-8",
        )
    else:
        raise ValueError("Auth plan output must be .json, .yaml, or .yml")


def read_auth_plan(path: Path) -> AuthPlan:
    """Load a reviewable authentication plan without resolving secret values."""

    suffix = path.suffix.lower()
    if suffix == ".json":
        data = json.loads(path.read_text(encoding="utf-8"))
    elif suffix in {".yaml", ".yml"}:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    else:
        raise ValueError("Auth plan input must be .json, .yaml, or .yml")
    if not isinstance(data, dict):
        raise ValueError("Auth plan must be a JSON/YAML object")
    return AuthPlan.model_validate(data)


def write_test_script(
    cases: list[TestCase],
    path: Path,
    *,
    auth_plan: AuthPlan | None = None,
    auth_hook: AuthHook | None = None,
) -> None:
    """Generate a standalone pytest/httpx script with optional authentication."""

    if path.suffix.lower() != ".py":
        raise ValueError("Python test script output must use .py")
    cases_payload = json.dumps(
        [case.model_dump(mode="json") for case in cases],
        ensure_ascii=False,
        indent=2,
    )
    auth_payload = json.dumps(
        auth_plan.model_dump(mode="json", exclude_none=True) if auth_plan else None,
        ensure_ascii=False,
        indent=2,
    )
    hook_payload = json.dumps(
        auth_hook.model_dump(mode="json") if auth_hook else None,
        ensure_ascii=False,
        indent=2,
    )
    source = _script_source(cases_payload, auth_payload, hook_payload)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source, encoding="utf-8")


def _script_source(cases_payload: str, auth_payload: str, hook_payload: str) -> str:
    return f'''"""Generated by LingTest CLI. Review before running."""

import hashlib
import importlib.util
import json
import os
import base64
from pathlib import Path

import httpx
import pytest

CASES = json.loads(r"""{cases_payload}""")
AUTH_PLAN = json.loads(r"""{auth_payload}""")
AUTH_HOOK = json.loads(r"""{hook_payload}""")
BASE_URL = os.environ.get("LINGTEST_BASE_URL", "http://localhost:8000")
TIMEOUT = float(os.environ.get("LINGTEST_TIMEOUT", "10"))


def _env_value(value):
    if isinstance(value, str) and value.startswith("${{") and value.endswith("}}"):
        return os.environ[value[2:-1]]
    return value


def _json_path(payload, path):
    current = payload
    for part in path.split("."):
        current = current[part]
    return current


def _build_authenticated_client():
    client = httpx.Client(base_url=BASE_URL.rstrip("/"), timeout=TIMEOUT)
    if any(case.get("requires_auth") for case in CASES) and (
        not AUTH_PLAN or AUTH_PLAN.get("kind") in {{None, "none"}}
    ) and not AUTH_HOOK:
        client.close()
        raise RuntimeError(
            "Protected API cases require a reviewed auth plan or approved authentication hook"
        )
    if not AUTH_PLAN or AUTH_PLAN.get("kind") in {{None, "none", "custom_hook"}}:
        return client
    kind = AUTH_PLAN.get("kind")
    for name in AUTH_PLAN.get("required_env") or []:
        if not os.environ.get(name):
            client.close()
            raise RuntimeError(f"Required authentication environment variable {{name}} is not set")
    if kind == "unknown":
        client.close()
        raise RuntimeError("Authentication plan is unknown; resolve auth details before testing")
    if kind == "basic":
        username = os.environ[AUTH_PLAN.get("username_env") or "LINGTEST_BASIC_USERNAME"]
        password = os.environ[AUTH_PLAN.get("password_env") or "LINGTEST_BASIC_PASSWORD"]
        token = base64.b64encode(f"{{username}}:{{password}}".encode()).decode()
        client.headers["Authorization"] = f"Basic {{token}}"
        return client
    if kind == "api_key":
        token_name = AUTH_PLAN.get("token_env") or "LINGTEST_API_KEY"
        _apply_token(client, AUTH_PLAN.get("apply") or {{}}, os.environ[token_name])
        return client
    login = AUTH_PLAN.get("login")
    if not login:
        if kind in {{"bearer", "cookie"}}:
            token_name = AUTH_PLAN.get("token_env") or (
                "LINGTEST_COOKIE_VALUE" if kind == "cookie" else "LINGTEST_BEARER_TOKEN"
            )
            _apply_token(client, AUTH_PLAN.get("apply") or {{}}, os.environ[token_name])
            return client
        client.close()
        raise RuntimeError("Authentication plan is missing login details")
    body = {{name: _env_value(value) for name, value in login.get("body", {{}}).items()}}
    request_args = {{login.get("content_type", "json"): body}}
    response = client.request(login.get("method", "POST"), login["path"], **request_args)
    response.raise_for_status()
    if AUTH_PLAN["kind"] == "bearer":
        token_path = (AUTH_PLAN.get("extract") or {{}}).get("json_path")
        application = AUTH_PLAN.get("apply") or {{}}
        if not token_path or not application.get("header"):
            raise RuntimeError("Bearer authentication plan is incomplete")
        token = _json_path(response.json(), token_path)
        template = application.get("template") or "Bearer {{token}}"
        client.headers[application["header"]] = template.format(token=token)
    return client


def _apply_token(client, application, token):
    template = application.get("template") or "{{token}}"
    value = template.format(token=token)
    if application.get("header"):
        client.headers[application["header"]] = value
    elif application.get("query_name"):
        client.params = {{**dict(client.params), application["query_name"]: value}}
    elif application.get("cookie_name"):
        client.cookies.set(application["cookie_name"], value)
    else:
        raise RuntimeError("Authentication plan has no application location")


def _load_auth_hook():
    if not AUTH_HOOK:
        return None
    path = Path(AUTH_HOOK["path"])
    if not path.is_absolute():
        path = Path.cwd() / path
    source = path.read_bytes()
    digest = hashlib.sha256(source).hexdigest()
    if digest != AUTH_HOOK["sha256"]:
        raise RuntimeError("Authentication hook changed after script generation; review again")
    spec = importlib.util.spec_from_file_location("lingtest_generated_auth_hook", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Cannot load authentication hook: {{path}}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return getattr(module, AUTH_HOOK["function"])


@pytest.fixture(scope="session")
def api_client():
    client = _build_authenticated_client()
    yield client
    client.close()


@pytest.fixture(scope="session")
def auth_hook():
    return _load_auth_hook()


@pytest.mark.parametrize("case", CASES, ids=lambda case: case["id"])
def test_api_case(case, api_client, auth_hook):
    login = (AUTH_PLAN or {{}}).get("login") or {{}}
    if (
        login
        and case["method"].upper() == login.get("method", "POST").upper()
        and case["path"].strip("/")
        == login.get("path", "").split("?", 1)[0].strip("/")
    ):
        pytest.skip("Token endpoint was exercised during authentication setup")
    headers = dict(case.get("headers") or {{}})
    request = api_client.build_request(
        case["method"],
        case["path"],
        params=case.get("query") or {{}},
        headers=headers,
        json=case.get("body"),
    )
    if auth_hook is not None:
        auth_hook(request)
    response = api_client.send(request)
    assert response.status_code == case["expected_status"], (
        f'{{case["id"]}} expected HTTP {{case["expected_status"]}}, '
        f"got {{response.status_code}}: {{response.text[:1000]}}"
    )
'''
