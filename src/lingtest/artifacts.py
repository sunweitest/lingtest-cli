"""Read and write executable API datasets and generated Python scripts."""

import json
from pathlib import Path

import yaml

from lingtest.models import TestCase


def read_cases(path: Path) -> list[TestCase]:
    suffix = path.suffix.lower()
    if suffix == ".json":
        data = json.loads(path.read_text(encoding="utf-8"))
    elif suffix in {".yaml", ".yml"}:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    else:
        raise ValueError("Executable cases must be .json, .yaml, or .yml")
    if not isinstance(data, list):
        raise ValueError("Executable case dataset must be a list")
    return [TestCase.model_validate(item) for item in data]


def write_cases(cases: list[TestCase], path: Path) -> None:
    suffix = path.suffix.lower()
    path.parent.mkdir(parents=True, exist_ok=True)
    data = [case.model_dump(mode="json") for case in cases]
    if suffix == ".json":
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    elif suffix in {".yaml", ".yml"}:
        path.write_text(
            yaml.safe_dump(data, allow_unicode=True, sort_keys=False),
            encoding="utf-8",
        )
    else:
        raise ValueError("Executable case output must be .json, .yaml, or .yml")


def write_test_script(cases: list[TestCase], path: Path) -> None:
    """Generate a standalone pytest/httpx script."""
    if path.suffix.lower() != ".py":
        raise ValueError("Python test script output must use .py")
    payload = json.dumps(
        [case.model_dump(mode="json") for case in cases],
        ensure_ascii=False,
        indent=2,
    )
    source = f'''"""Generated by LingTest CLI. Review before running."""

import json
import os

import httpx
import pytest

CASES = json.loads(r"""{payload}""")
BASE_URL = os.environ.get("LINGTEST_BASE_URL", "http://localhost:8000")
TIMEOUT = float(os.environ.get("LINGTEST_TIMEOUT", "10"))


@pytest.mark.parametrize("case", CASES, ids=lambda case: case["id"])
def test_api_case(case):
    headers = dict(case.get("headers") or {{}})
    response = httpx.request(
        case["method"],
        BASE_URL.rstrip("/") + case["path"],
        params=case.get("query") or {{}},
        headers=headers,
        json=case.get("body"),
        timeout=TIMEOUT,
    )
    assert response.status_code == case["expected_status"], (
        f'{{case["id"]}} expected HTTP {{case["expected_status"]}}, '
        f"got {{response.status_code}}: {{response.text[:1000]}}"
    )
'''
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source, encoding="utf-8")
